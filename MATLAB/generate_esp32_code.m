function generate_esp32_code(LINK)
% GENERATE_ESP32_CODE  MATLAB writes the Arduino (ESP32) code from the model.
%
%   >> generate_esp32_code          % WiFi  (default)
%   >> generate_esp32_code('bt')    % Bluetooth instead
%
% Everything the ESP32 needs is calculated here from robot_params.m / robot_ss.m:
%   encoder counts per turn, supply voltage, sample time, PI gains (pole placement),
%   RST coefficients (Diophantine), pins, motor directions.
% Output: ..\ESP32_Robot\ESP32_Robot.ino   (one file - open it in Arduino IDE and Upload)

if nargin < 1, LINK = 'wifi'; end
here = fileparts(mfilename('fullpath'));
P = robot_params(false);  S = robot_ss(P);

%% ---------------- pins (ESP32 DevKit) - same as the circuit diagram
pin.ENA = 25;  pin.IN1 = 26;  pin.IN2 = 27;        % left motor  (L298N)
pin.ENB = 13;  pin.IN3 = 32;  pin.IN4 = 33;        % right motor (L298N)
pin.ENC_LA = 18;  pin.ENC_LB = 19;                 % left encoder  C1 C2
pin.ENC_RA = 16;  pin.ENC_RB = 17;                 % right encoder C1 C2
dirs.DIR_L = 1;  dirs.DIR_R = 1;                   % change after test_robot_connection if needed
dirs.ENC_SIGN_L = 1;  dirs.ENC_SIGN_R = -1;

%% ---------------- WiFi network made by the ESP32
wifi.SSID = 'Robot_ESP32';
wifi.PASS = '12345678';

%% ---------------- numbers from the model
CPR = P.PPR * P.N * 4;                             % x4 quadrature
[r0, r1, T0] = rst_coeffs(P, S);

tok = struct( ...
    'DATE',      datestr(now, 'yyyy-mm-dd HH:MM'), ...
    'USE_WIFI',  num2str(~strcmpi(LINK, 'bt')), ...
    'LINK_TEXT', link_text(LINK, wifi), ...
    'SSID', wifi.SSID, 'PASS', wifi.PASS, ...
    'CPR',  sprintf('%.1f', CPR), 'PPR', num2str(P.PPR), 'N', num2str(P.N), ...
    'VSUP', sprintf('%.2f', P.Vmax), 'VBAT', sprintf('%.1f', P.V_bat), 'VDROP', sprintf('%.1f', P.V_drop), ...
    'VMAX', sprintf('%.2f', P.Vmax), 'TS', sprintf('%.3f', P.Ts), ...
    'KP', sprintf('%.4f', S.Kp), 'KI', sprintf('%.4f', S.Ki), ...
    'R0', sprintf('%.5f', r0), 'R1', sprintf('%.5f', r1), 'T0', sprintf('%.5f', T0));
fn = [fieldnames(pin); fieldnames(dirs)];
for k = 1:numel(fn)
    if isfield(pin, fn{k}), tok.(fn{k}) = num2str(pin.(fn{k})); else, tok.(fn{k}) = num2str(dirs.(fn{k})); end
end

%% ---------------- fill the template
code = fileread(fullfile(here, 'esp32_template.ino.txt'));
names = fieldnames(tok);
for k = 1:numel(names)
    code = strrep(code, ['{{' names{k} '}}'], tok.(names{k}));
end
left = regexp(code, '\{\{\w+\}\}', 'match');
if ~isempty(left), error('not filled: %s', strjoin(unique(left), ', ')); end

outdir = fullfile(fileparts(here), 'ESP32_Robot');          % Arduino: folder name = file name
if ~exist(outdir, 'dir'), mkdir(outdir); end
outfile = fullfile(outdir, 'ESP32_Robot.ino');
fid = fopen(outfile, 'w');  fwrite(fid, code);  fclose(fid);

fprintf('\n=========== ESP32 code generated by MATLAB ===========\n');
fprintf('file      : %s\n', outfile);
fprintf('link      : %s\n', tok.LINK_TEXT);
fprintf('CPR       : %.0f counts / wheel turn\n', CPR);
fprintf('V supply  : %.2f V    Ts = %.3f s\n', P.Vmax, P.Ts);
fprintf('PI        : Kp = %.4f  Ki = %.4f\n', S.Kp, S.Ki);
fprintf('RST       : R0 = %.5f  R1 = %.5f  T0 = %.5f\n', r0, r1, T0);
fprintf('-> open it in Arduino IDE, Board "ESP32 Dev Module", Upload.\n\n');
if ispc, try, winopen(outdir); catch, end, end
end

function t = link_text(LINK, wifi)
if strcmpi(LINK, 'bt')
    t = 'Bluetooth Classic, name Robot_ESP32';
else
    t = sprintf('WiFi access point "%s" (password %s), robot IP 192.168.4.1, UDP port 4210', wifi.SSID, wifi.PASS);
end
end
